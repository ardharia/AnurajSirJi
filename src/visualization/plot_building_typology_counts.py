# src/visualization/plot_building_typology_counts.py
"""Plot the number of buildings per typology.

The script reads ``outputs/building_summary.csv`` (generated by ``run_full_pipeline.py``),
counts how many buildings belong to each typology, and saves a bar chart as
``outputs/building_typology_counts.png``.
"""

from __future__ import annotations

import pathlib
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd


def main() -> None:
    project_root = Path(__file__).resolve().parents[2]
    outputs_dir = project_root / "outputs"
    summary_path = outputs_dir / "building_summary.csv"
    if not summary_path.exists():
        raise FileNotFoundError(f"Building summary CSV not found at {summary_path}. Run run_full_pipeline.py first.")

    df = pd.read_csv(summary_path)
    # Ensure typology column exists
    if "typology" not in df.columns:
        raise KeyError("Column 'typology' missing in building_summary.csv")

    counts = df["typology"].value_counts().sort_index()
    plt.figure(figsize=(10, 6))
    counts.plot(kind="bar", color="#4C78A8")
    plt.title("Number of Buildings per Typology")
    plt.xlabel("Typology")
    plt.ylabel("Number of Buildings")
    plt.xticks(rotation=45, ha="right")
    plt.tight_layout()
    out_path = outputs_dir / "building_typology_counts.png"
    plt.savefig(out_path, dpi=150)
    plt.close()
    print(f"Bar chart saved to {out_path}")


if __name__ == "__main__":
    main()
